import { expect, test } from '@playwright/test'

test('persistent rail restores context shortcuts and keeps account at the bottom', async ({
  page,
}) => {
  await page.goto('/')
  await page.getByRole('button', { name: '收起侧栏' }).click()
  const rail = page.getByRole('complementary', { name: '窄侧栏' })
  await expect(rail).toBeVisible()
  expect((await rail.boundingBox())!.width).toBe(56)
  await rail.getByRole('button', { name: '当前工作空间对话' }).click()
  await expect(page.getByRole('heading', { name: '工作空间对话', exact: true })).toBeVisible()
  await rail.getByRole('button', { name: '当前项目对话' }).click()
  await expect(page.getByRole('heading', { name: 'GatewayKit', exact: true })).toBeVisible()
  await rail.getByRole('button', { name: '当前需求对话' }).click()
  await expect(page.getByRole('heading', { name: '网关稳定性', exact: true })).toBeVisible()
  const avatar = await rail.getByRole('button', { name: '个人菜单' }).boundingBox()
  expect(avatar!.y).toBeGreaterThan(800)
  await rail.getByRole('button', { name: '个人菜单' }).click()
  await expect(page.getByRole('menuitem', { name: '设置', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '展开侧栏' }).click()
  await expect(page.getByRole('complementary', { name: '工作空间导航' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Agent 管理' })).toHaveCount(0)
  await expect(page.locator('.navigation').getByText('待开始', { exact: true })).toHaveCount(0)
  await expect(
    page.locator('.composer-actions').getByRole('button', { name: '当前需求' }),
  ).toHaveCount(0)
})

test('project trees toggle without changing conversation and reveal projects 5 then 3 at a time', async ({
  page,
}) => {
  await page.goto('/')
  await expect(page.locator('.project-tree')).toHaveCount(5)
  await page.getByRole('button', { name: '展示更多', exact: true }).click()
  await expect(page.locator('.project-tree')).toHaveCount(8)
  await expect(page.getByRole('button', { name: '展示更多', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '展示更多', exact: true }).click()
  await expect(page.locator('.project-tree')).toHaveCount(10)
  await expect(page.getByRole('button', { name: '展示更多', exact: true })).toHaveCount(0)
  const header = page.getByRole('heading', { name: '网关稳定性', exact: true })
  await page.getByRole('button', { name: '收起项目 GatewayKit', exact: true }).click()
  await expect(page.locator('[data-project-id="gatewaykit"] .project-children')).toHaveCount(0)
  await expect(header).toBeVisible()
  await page.getByRole('button', { name: '展开项目 GatewayKit', exact: true }).click()
  const children = page.locator('[data-project-id="gatewaykit"] .project-children')
  await expect(children.getByRole('button').first()).toHaveText('项目对话')
  const edit = page.getByRole('button', { name: '编辑项目 GatewayKit', exact: true })
  await page.getByRole('textbox', { name: '发送消息', exact: true }).focus()
  await page.locator('.chat-panel').hover()
  await expect(edit).toHaveCSS('opacity', '0')
  await page.getByRole('button', { name: '收起项目 GatewayKit', exact: true }).hover()
  await expect(edit).toHaveCSS('opacity', '0.6')
})

test('project create/edit and requirement creation update the shared navigation and chat scope', async ({
  page,
}) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新建项目', exact: true }).click()
  await page.getByRole('textbox', { name: '项目名称' }).fill('客户门户')
  await page.getByRole('textbox', { name: '描述', exact: true }).fill('客户自助服务入口')
  await page.getByRole('dialog').getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.getByRole('heading', { name: '客户门户', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '收起项目 客户门户', exact: true }).hover()
  await page.getByRole('button', { name: '编辑项目 客户门户', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '描述', exact: true })).toHaveValue(
    '客户自助服务入口',
  )
  await page.getByRole('textbox', { name: '项目名称' }).fill('客户服务门户')
  await page.getByRole('dialog').getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('heading', { name: '客户服务门户', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '在客户服务门户中新建需求', exact: true }).click()
  await page.getByRole('textbox', { name: '需求名称' }).fill('工单查询')
  await page.getByRole('textbox', { name: '描述', exact: true }).fill('支持查询历史工单')
  await page.getByRole('dialog').getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工单查询', exact: true })).toBeVisible()
  const requirement = page.locator('.requirement-row').filter({ hasText: '工单查询' })
  await expect(requirement.locator('.project-children')).toHaveCount(0)
  await page.getByRole('button', { name: '在客户服务门户中新建需求', exact: true }).click()
  await page.getByRole('textbox', { name: '需求名称' }).fill('工单查询')
  await page.getByRole('dialog').getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('已有同名需求')
})

test('Agent selection swaps Todo for Memory and narrow rail stays available', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '与Sam对话', exact: true }).click()
  await expect(page.getByRole('region', { name: '任务栏', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Memory', exact: true })).toBeVisible()
  await expect(page.getByRole('img', { name: /Sam 的知识图谱占位/ })).toBeVisible()
  await page.getByRole('textbox', { name: '发送消息', exact: true }).fill('查看记忆规划')
  await page.getByRole('textbox', { name: '发送消息', exact: true }).press('Enter')
  await expect(page.locator('.messages .message').last()).toContainText('Sam')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('complementary', { name: '窄侧栏' })).toBeVisible()
  await page.getByRole('button', { name: 'Memory', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Memory 栏' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '当前需求对话', exact: true }).click()
  await page.getByRole('button', { name: '任务', exact: true }).click()
  await expect(page.getByRole('region', { name: '任务栏', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Memory 栏' })).toHaveCount(0)
})
